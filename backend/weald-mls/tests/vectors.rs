/// Files in the upstream `test-vectors/` directory that this suite deliberately does not
/// vendor, each with the reason. Written down rather than left implicit, because a reader
/// checking whether the gate is honest needs to see what was left out and why.
///
/// - `key-schedule.json`: the vector fixes an `init_secret` and a per-epoch
///   `commit_secret` and asks for the derived epoch secrets. Injecting those means
///   constructing OpenMLS's `KeySchedule` directly, which is crate-internal and reachable
///   only through the `test-utils` feature. Our seam's only key-schedule surface is
///   `Session::export`, and that is bound to a live group at a real epoch, so there is no
///   point to inject at. The provider wiring the vector would have exercised is covered by
///   `crypto-basics.json` instead, which drives the same `RustCrypto` instance
///   `store::Provider` hands OpenMLS.
/// - `passive-client-welcome.json`, `passive-client-handling-commit.json`,
///   `passive-client-random.json`: each supplies a joiner's `init_priv`,
///   `encryption_priv` and `signature_priv` and expects a client to join with them.
///   `Device` mints its own signing key on first use and keeps it in its own encrypted
///   store (`session::load_or_create_signer`), and the seam has no key-import function at
///   all. That is a deliberate property of the design, not an oversight, so these vectors
///   cannot be expressed without widening the twelve-function seam for a test. The joining
///   path they would prove is proved instead by `tests/session.rs`, which joins a real
///   welcome produced by a real add.
/// - `secret-tree.json`, `message-protection.json`, `transcript-hashes.json`,
///   `treekem.json`, `tree-validation.json`, `tree-operations.json`, `tree-math.json`,
///   `psk_secret.json`, `deserialization.json`: all address OpenMLS internals (the secret
///   tree, the transcript hash chain, tree math, PSK derivation) that our seam never
///   touches as bytes and cannot reach as types. Re-testing them here would be re-testing
///   OpenMLS, which is exactly what the spec says these vectors are not for.
