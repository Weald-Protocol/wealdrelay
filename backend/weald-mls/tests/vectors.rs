//! RFC 9420's interop test vectors, driven through this binding rather than through
//! OpenMLS's own suite.
//!
//! `specs/backend/relay/mls-binding.md` asks for exactly this and says why: "RFC 9420 test
//! vectors, run against our binding rather than only against OpenMLS's own suite, so a
//! mistake in our marshalling is caught." OpenMLS already runs these vectors against its
//! internal types. That proves OpenMLS implements the RFC. It proves nothing at all about
//! the layer this crate adds on top: the `tls_serialize` and `tls_deserialize` pairings in
//! `src/session.rs`, the choice of which body a given seam function will accept, the
//! `Malformed` versus `Protocol` distinction the C ABI reports, and the provider
//! `src/store.rs` assembles out of `RustCrypto` and SQLite. Every one of those is ours and
//! every one of them can be wrong while OpenMLS is right.
//!
//! So each vector here enters through a public function of the seam: `Device::key_package`,
//! `Device::join_welcome`, `Device::join_external`, `Session::add` (which is
//! `read_key_package`), `Session::process`, `Session::ratchet_tree`, and the provider
//! reached through `Device::provider`.
//!
//! What a failure here means, by test:
//!
//! - An acceptance failure (a conformant vector coming back `Malformed`) means our decoder
//!   rejects messages a conformant peer will really send. In the shipped product that is a
//!   device that cannot be invited, cannot join, or drops group traffic on the floor.
//! - A re-encoding failure means the bytes we put on the wire are not the bytes the RFC
//!   describes, so every other implementation refuses us. `Device::key_package` publishes
//!   to the relay and `Session::ratchet_tree` hands a tree to a joiner, and both are
//!   compared here against vectors generated by other implementations.
//! - A negative-control failure means the acceptance assertions have no teeth: a decoder
//!   that accepted everything would pass them.
//! - A crypto-basics failure means `store::Provider` is wired to something that is not
//!   RFC 9420's key schedule primitives, which would be a silent interoperability break
//!   with no error message anywhere.
//!
//! The corpus is vendored under `tests/vectors/` with its provenance in
//! `tests/vectors/README.md`, and the first test in this file re-derives the digests, so a
//! corpus that drifted from the commit it claims to come from fails before anything is
//! read from it. A vector corpus with no provenance is not a conformance proof.
//!
//! Every test counts what it ran and what it skipped and asserts both exactly. A
//! conformance suite that ran zero vectors and reported success is the failure mode this
//! design is against, so no test here can pass by finding nothing to do.

